#!/usr/bin/env node
/**
 * Build the core stylesheets into packages/core/dist:
 *
 *   dist/tokens.css  the --mikedown-* token defaults (copy of src/styles/tokens.css)
 *   dist/styles.css  KaTeX import + tokens + the 21 component files, in cascade order
 *
 * Plain Node, no dependencies. Relative `@import "./x.css"` lines inside a
 * component file (editor.css pulls in theme.css) are inlined in place. The
 * VS Code extension does not use this output: it loads the source files one
 * by one plus src/webview/vscode-theme.css (see markdownEditorProvider.ts).
 *
 * Usage: node scripts/build-css.mjs   (npm run build:css -w packages/core)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const pkgDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = path.join(pkgDir, 'src', 'styles');
const outDir = path.join(pkgDir, 'dist');

/** Cascade order. Must match the list in markdownEditorProvider.ts#getWebviewContent. */
export const ORDER = [
  'editor.css',
  'tables.css',
  'images.css',
  'codeblocks.css',
  'mermaid.css',
  'math.css',
  'footnotes.css',
  'links.css',
  'findreplace.css',
  'contextmenu.css',
  'tablepicker.css',
  'tabledrag.css',
  'tasklist.css',
  'linkautocomplete.css',
  'toolbar-dropdown.css',
  'outline-sidebar.css',
  'emojipicker.css',
  'slashcommands.css',
  'spellcheck.css',
  'settings-modal.css',
  'ai.css',
  'ai-rewrite.css',
];

/** Inline relative @import lines (recursively); returns the CSS and the files it pulled in. */
function inline(file, seen) {
  const abs = path.join(srcDir, file);
  if (seen.has(abs)) {throw new Error(`build-css: circular @import of ${file}`);}
  seen.add(abs);
  const css = fs.readFileSync(abs, 'utf8');
  return css.replace(/^@import\s+(?:url\()?["'](\.\/[^"']+)["']\)?\s*;\s*$/gm, (_m, rel) => {
    const child = path.normalize(path.join(path.dirname(file), rel));
    return `/* ── ${child} (inlined from ${file}) ── */\n${inline(child, seen)}`;
  });
}

function build() {
  const seen = new Set();
  const parts = ORDER.map((f) => `/* ═══ ${f} ═══ */\n${inline(f, seen)}`);

  // Every stylesheet in src/styles must be either listed, imported by a listed
  // file, or tokens.css, so a new file cannot silently drop out of the bundle.
  const all = fs.readdirSync(srcDir).filter((f) => f.endsWith('.css') && f !== 'tokens.css');
  const missing = all.filter((f) => !seen.has(path.join(srcDir, f)));
  if (missing.length) {
    throw new Error(`build-css: not in ORDER and not @imported: ${missing.join(', ')}`);
  }

  const tokens = fs.readFileSync(path.join(srcDir, 'tokens.css'), 'utf8');
  const banner = '/* @mikedown/core styles.css (generated by scripts/build-css.mjs, do not edit) */\n';
  // @import must precede every other rule. Consumers' bundlers (Angular CLI,
  // Vite, webpack css-loader) resolve the bare specifier from node_modules.
  const styles = `${banner}@import 'katex/dist/katex.min.css';\n\n/* ═══ tokens.css ═══ */\n${tokens}\n${parts.join('\n')}`;

  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, 'tokens.css'), tokens);
  fs.writeFileSync(path.join(outDir, 'styles.css'), styles);
  const kb = (n) => `${(n / 1024).toFixed(1)} kB`;
  console.log(`build-css: dist/styles.css ${kb(Buffer.byteLength(styles))}, dist/tokens.css ${kb(Buffer.byteLength(tokens))}`);
}

// Build only when run as a script, so tests can import ORDER.
if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  build();
}
